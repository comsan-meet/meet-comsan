<?php
/**
 * COMSAN Meeting System - Database & Cloud Config API
 * Supports both MySQL / MariaDB and Supabase Realtime credentials
 * Supports both GET and POST to bypass InfinityFree OpenResty 403 errors
 */

error_reporting(0);
ini_set('display_errors', '0');

header('Access-Control-Allow-Origin: *');
header('Access-Control-Allow-Methods: GET, POST, OPTIONS');
header('Access-Control-Allow-Headers: Content-Type, Authorization, X-Requested-With');
header('Content-Type: application/json; charset=utf-8');

if ($_SERVER['REQUEST_METHOD'] === 'OPTIONS') {
    http_response_code(200);
    exit;
}

$configFile = __DIR__ . '/db_config.json';
$rootConfigPhp = file_exists(__DIR__ . '/config.php') ? __DIR__ . '/config.php' : (file_exists(__DIR__ . '/../config.php') ? __DIR__ . '/../config.php' : (file_exists(__DIR__ . '/../../config.php') ? __DIR__ . '/../../config.php' : null));

// Check if request intends to SAVE credentials
$isSave = false;
$data = [];

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    $raw = file_get_contents('php://input');
    if ($raw) {
        $json = json_decode($raw, true);
        if ($json && is_array($json)) {
            $data = $json;
            $isSave = true;
        }
    }
    if (!$isSave && !empty($_POST)) {
        $data = $_POST;
        $isSave = true;
    }
}

// Support GET saving (Critical fallback when InfinityFree blocks POST with 403)
if (!$isSave && (isset($_GET['action']) && $_GET['action'] === 'save' || isset($_GET['save']))) {
    $data = $_GET;
    $isSave = true;
}

if ($isSave) {
    // Load existing config so partial updates don't overwrite other settings
    $existing = [];
    if (file_exists($configFile)) {
        $existing = json_decode(file_get_contents($configFile), true) ?: [];
    }

    $host = isset($data['host']) ? trim($data['host']) : ($existing['host'] ?? 'localhost');
    $port = isset($data['port']) ? trim($data['port']) : ($existing['port'] ?? '3306');
    $dbname = isset($data['dbname']) ? trim($data['dbname']) : ($existing['dbname'] ?? 'comsan_meeting');
    $user = isset($data['user']) ? trim($data['user']) : ($existing['user'] ?? 'root');
    $pass = isset($data['pass']) ? $data['pass'] : ($existing['pass'] ?? '');

    $supabaseUrl = isset($data['supabase_url']) ? trim($data['supabase_url']) : ($existing['supabase_url'] ?? '');
    $supabaseKey = isset($data['supabase_key']) ? trim($data['supabase_key']) : ($existing['supabase_key'] ?? '');

    $toSave = [
        'host' => $host,
        'port' => $port,
        'dbname' => $dbname,
        'user' => $user,
        'pass' => $pass,
        'supabase_url' => $supabaseUrl,
        'supabase_key' => $supabaseKey,
        'updated_at' => date('Y-m-d H:i:s')
    ];

    @file_put_contents($configFile, json_encode($toSave, JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE));

    // Also update config.php if writable
    if ($rootConfigPhp && is_writable($rootConfigPhp)) {
        $phpCode = "<?php\n"
            . "/**\n * Database Configuration (config.php)\n * Generated by COMSAN Meeting System\n */\n"
            . "date_default_timezone_set('Asia/Bangkok');\n\n"
            . "define('DB_HOST', '" . addslashes($host) . "');\n"
            . "define('DB_PORT', '" . addslashes($port) . "');\n"
            . "define('DB_NAME', '" . addslashes($dbname) . "');\n"
            . "define('DB_USER', '" . addslashes($user) . "');\n"
            . "define('DB_PASS', '" . addslashes($pass) . "');\n"
            . "define('DB_CHARSET', 'utf8mb4');\n\n"
            . "try {\n"
            . "    \$dsn = \"mysql:host=\" . DB_HOST . \";port=\" . DB_PORT . \";dbname=\" . DB_NAME . \";charset=\" . DB_CHARSET;\n"
            . "    \$options = [\n"
            . "        PDO::ATTR_ERRMODE            => PDO::ERRMODE_EXCEPTION,\n"
            . "        PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,\n"
            . "        PDO::ATTR_EMULATE_PREPARES   => false,\n"
            . "        PDO::MYSQL_ATTR_INIT_COMMAND => \"SET NAMES \" . DB_CHARSET\n"
            . "    ];\n"
            . "    \$pdo = new PDO(\$dsn, DB_USER, DB_PASS, \$options);\n"
            . "    \$conn = \$pdo;\n"
            . "} catch (PDOException \$e) {\n"
            . "    error_log(\"Database Connection Error: \" . \$e->getMessage());\n"
            . "}\n";
        @file_put_contents($rootConfigPhp, $phpCode);
    }

    echo json_encode([
        'status' => 'success',
        'message' => 'บันทึกการตั้งค่าฐานข้อมูลลงเซิร์ฟเวอร์เรียบร้อยแล้ว ทุกอุปกรณ์จะใช้การตั้งค่าเดียวกัน',
        'data' => $toSave
    ], JSON_UNESCAPED_UNICODE);
    exit;
}

// GET Request: Load current DB & Supabase config
$saved = null;
if (file_exists($configFile)) {
    $saved = json_decode(@file_get_contents($configFile), true);
}

if (!$saved && $rootConfigPhp && file_exists($rootConfigPhp)) {
    @include_once $rootConfigPhp;
    if (defined('DB_HOST')) {
        $saved = [
            'host' => DB_HOST,
            'port' => defined('DB_PORT') ? DB_PORT : '3306',
            'dbname' => defined('DB_NAME') ? DB_NAME : 'comsan_meeting',
            'user' => defined('DB_USER') ? DB_USER : 'root',
            'pass' => defined('DB_PASS') ? DB_PASS : '',
            'supabase_url' => '',
            'supabase_key' => '',
            'updated_at' => null
        ];
    }
}

if (!$saved) {
    $saved = [
        'host' => 'localhost',
        'port' => '3306',
        'dbname' => 'comsan_meeting',
        'user' => 'root',
        'pass' => '',
        'supabase_url' => '',
        'supabase_key' => '',
        'updated_at' => null
    ];
}

echo json_encode([
    'status' => 'success',
    'data' => $saved
], JSON_UNESCAPED_UNICODE);
